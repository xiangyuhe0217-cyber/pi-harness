def render_study(task_id: str) -> str:
    item = STUDY.get(task_id)
    if not item:
        return ""
    lines = [
        "## 学习与面试",
        "",
        f"**主题**：{item['topic']}",
        "",
        f"**为什么**：{item['why']}",
        "",
        "**面试可能问**：",
        "",
    ]
    for question, answer in item["qa"]:
        lines.append(f"- **Q**：{question}")
        lines.append(f"  **A**：{answer}")
    lines.append("")
    return "\n".join(lines)
